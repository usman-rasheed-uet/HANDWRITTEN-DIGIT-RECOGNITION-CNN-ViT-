# ---------- Rebuild the exact model architectures (must match training) ----------
class DigitCNN(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 16, 3, padding=1)
        self.conv2 = nn.Conv2d(16, 32, 3, padding=1)
        self.act   = nn.ReLU()
        self.pool  = nn.MaxPool2d(2)
        self.fc1   = nn.Linear(32*2*2, 64)
        self.fc2   = nn.Linear(64, 10)
    def forward(self, x):
        x = self.act(self.conv1(x)); x = self.pool(x)
        x = self.act(self.conv2(x)); x = self.pool(x)
        x = x.flatten(1)
        x = self.act(self.fc1(x))
        return self.fc2(x)

def patchify(x):
    p = x.view(-1, 1, 4, 2, 4, 2)
    p = p.permute(0, 1, 2, 4, 3, 5)
    return p.reshape(-1, 16, 4)

class DigitViT(nn.Module):
    def __init__(self, embed_dim=32, n_heads=4, n_layers=2, dropout=0.1):
        super().__init__()
        self.patch_proj = nn.Linear(4, embed_dim)
        self.pos_embed  = nn.Parameter(torch.zeros(1, 16, embed_dim))
        enc = nn.TransformerEncoderLayer(
            d_model=embed_dim, nhead=n_heads,
            dim_feedforward=64, dropout=dropout, batch_first=True)
        self.encoder = nn.TransformerEncoder(enc, num_layers=n_layers)
        self.norm    = nn.LayerNorm(embed_dim)
        self.head    = nn.Linear(embed_dim, 10)
    def forward(self, x):
        t = self.patch_proj(patchify(x)) + self.pos_embed
        t = self.encoder(t)
        t = self.norm(t)
        return self.head(t.mean(dim=1))

# ---------- Load checkpoints once (cached) ----------
@st.cache_resource
def load_models():
    cnn = DigitCNN().to(device)
    cnn.load_state_dict(torch.load("cnn_digit.pt", map_location=device))
    cnn.eval()

    vit = DigitViT().to(device)
    vit.load_state_dict(torch.load("vit_digit.pt", map_location=device))
    vit.eval()

    with open("preprocess_meta.json") as f:
        meta = json.load(f)
    return cnn, vit, meta

# ---------- Upload pipeline ----------
def prepare_upload(pil_img, threshold=10):
    if pil_img is None:
        raise ValueError("No file uploaded.")
    img = pil_img.convert("L")
    arr = np.asarray(img, dtype=np.uint8)
    if arr.mean() > 127:                                # Invert if bg is bright.
        img = Image.fromarray(255 - arr)
        arr = np.asarray(img, dtype=np.uint8)
    ys, xs = np.where(arr > threshold)
    if len(xs) == 0:
        raise ValueError("Blank image (no strokes).")
    crop = arr[ys.min():ys.max()+1, xs.min():xs.max()+1]
    h, w = crop.shape
    side = max(h, w)
    canvas = np.zeros((side, side), dtype=np.uint8)
    canvas[(side-h)//2:(side-h)//2+h, (side-w)//2:(side-w)//2+w] = crop
    small = Image.fromarray(canvas).resize((8, 8), Image.LANCZOS)
    arr8  = np.asarray(small, dtype=np.float32) / 255.0
    return torch.from_numpy(arr8).unsqueeze(0).unsqueeze(0), arr8

